    // ---------------------------------------------------------------- Accelerator API

    @Override
    public List<BlockPoint> findChunks(long seed, long minX, long maxX, long minZ, long maxZ,
                                       boolean circleFilter, int centerX, int centerZ, long radiusSq) {
        try {
            return findChunksGpu(seed, minX, maxX, minZ, maxZ, circleFilter, centerX, centerZ, radiusSq);
        } catch (Throwable t) {
            return this.cpu.findChunks(seed, minX, maxX, minZ, maxZ, circleFilter, centerX, centerZ, radiusSq);
        }
    }

    @Override
    public boolean[] pruneByDensity(List<BlockPoint> candidates, int clusterRadius, int minStructures) {
        int[] scores = densityScores(candidates, clusterRadius);
        boolean[] keep = new boolean[candidates.size()];
        for (int i = 0; i < keep.length; i++) {
            keep[i] = scores[i] >= minStructures;
        }
        return keep;
    }

    @Override
    public int[] densityScores(List<BlockPoint> candidates, int clusterRadius) {
        try {
            return densityCountsGpu(candidates, clusterRadius);
        } catch (Throwable t) {
            return this.cpu.densityScores(candidates, clusterRadius);
        }
    }

    @Override
    public List<BlockPoint> gridAggregateAndSelect(List<BlockPoint> candidates, int clusterRadius,
                                                   int gridSizeBlocks, int topK) {
        try {
            return gridAggregateAndSelectGpu(candidates, clusterRadius, gridSizeBlocks, topK);
        } catch (Throwable t) {
            return this.cpu.gridAggregateAndSelect(candidates, clusterRadius, gridSizeBlocks, topK);
        }
    }

    /**
     * GPU grid aggregation: reuses {@link #densityScores} (2R neighbour count per candidate),
     * accumulates the total density score per grid cell with {@code gridAggregateKernel}, then
     * selects the top-K cells on the CPU (grid counts are far smaller than candidate counts) and
     * returns the candidates in the selected cells.
     */
    private List<BlockPoint> gridAggregateAndSelectGpu(List<BlockPoint> candidates, int clusterRadius,
                                                       int gridSizeBlocks, int topK) {
        int n = candidates.size();
        if (n == 0 || topK <= 0) {
            return new ArrayList<>();
        }
        int[] scores = densityScores(candidates, clusterRadius);

        int minX = Integer.MAX_VALUE;
        int maxX = Integer.MIN_VALUE;
        int minZ = Integer.MAX_VALUE;
        int maxZ = Integer.MIN_VALUE;
        for (BlockPoint p : candidates) {
            minX = Math.min(minX, p.x());
            maxX = Math.max(maxX, p.x());
            minZ = Math.min(minZ, p.z());
            maxZ = Math.max(maxZ, p.z());
        }
        long spanX = (long) maxX - minX;
        long spanZ = (long) maxZ - minZ;
        int gridDimX = (int) (spanX / gridSizeBlocks + 1);
        int gridDimZ = (int) (spanZ / gridSizeBlocks + 1);
        long cellsLong = (long) gridDimX * gridDimZ;
        if (cellsLong > DENSITY_CELL_LIMIT) {
            // Coarsen the aggregation grid so the cell count stays bounded (a larger cell only
            // merges adjacent cells; selection is still by total density per cell).
            long minCell = (long) Math.ceil(Math.max(spanX, spanZ) / Math.sqrt(DENSITY_CELL_LIMIT));
            int enlarged = Math.max(gridSizeBlocks, (int) Math.min(Integer.MAX_VALUE, minCell));
            gridDimX = (int) (spanX / enlarged + 1);
            gridDimZ = (int) (spanZ / enlarged + 1);
            gridSizeBlocks = enlarged;
        }
        int cells = gridDimX * gridDimZ;

        int[] points = new int[n * 2];
        for (int i = 0; i < n; i++) {
            points[2 * i] = candidates.get(i).x();
            points[2 * i + 1] = candidates.get(i).z();
        }

        CUdeviceptr ptsPtr = new CUdeviceptr();
        cuMemAlloc(ptsPtr, (long) n * 8L);
        CUdeviceptr scoresPtr = new CUdeviceptr();
        cuMemAlloc(scoresPtr, (long) n * 4L);
        CUdeviceptr gridScoresPtr = new CUdeviceptr();
        cuMemAlloc(gridScoresPtr, (long) cells * 4L);
        CUdeviceptr gridCountsPtr = new CUdeviceptr();
        cuMemAlloc(gridCountsPtr, (long) cells * 4L);

        int[] gridScores;
        int[] cellOf = new int[n];
        try {
            cuMemcpyHtoD(ptsPtr, Pointer.to(points), (long) n * 8L);
            cuMemcpyHtoD(scoresPtr, Pointer.to(scores), (long) n * 4L);
            cuMemsetD32(gridScoresPtr, 0, cells);
            cuMemsetD32(gridCountsPtr, 0, cells);

            int grid = (int) Math.ceil(n / (double) BLOCK);
            cuLaunchKernel(fGridAggregate,
                    grid, 1, 1, BLOCK, 1, 1, 0, null,
                    Pointer.to(
                            Pointer.to(new int[]{n}),
                            Pointer.to(ptsPtr),
                            Pointer.to(scoresPtr),
                            Pointer.to(new int[]{minX}),
                            Pointer.to(new int[]{minZ}),
                            Pointer.to(new int[]{gridDimX}),
                            Pointer.to(new int[]{gridDimZ}),
                            Pointer.to(new int[]{gridSizeBlocks}),
                            Pointer.to(gridScoresPtr),
                            Pointer.to(gridCountsPtr)),
                    null);

            gridScores = new int[cells];
            cuMemcpyDtoH(Pointer.to(gridScores), gridScoresPtr, (long) cells * 4L);

            // Compute each candidate's cell on the CPU for the selection pass.
            for (int i = 0; i < n; i++) {
                int gx = (candidates.get(i).x() - minX) / gridSizeBlocks;
                int gz = (candidates.get(i).z() - minZ) / gridSizeBlocks;
                cellOf[i] = gz * gridDimX + gx;
            }
        } finally {
            cuMemFree(ptsPtr);
            cuMemFree(scoresPtr);
            cuMemFree(gridScoresPtr);
            cuMemFree(gridCountsPtr);
        }

        // CPU top-K cell selection (identical to CpuAccelerator).
        List<Integer> occupied = new ArrayList<>();
        for (int cell = 0; cell < cells; cell++) {
            if (gridScores[cell] > 0) {
                occupied.add(cell);
            }
        }
        occupied.sort((a, b) -> {
            int byScore = Integer.compare(gridScores[b], gridScores[a]);
            return byScore != 0 ? byScore : Integer.compare(a, b);
        });
        int keepCells = Math.min(topK, occupied.size());
        java.util.Set<Integer> selected = new java.util.HashSet<>(occupied.subList(0, keepCells));

        List<BlockPoint> retained = new ArrayList<>();
        for (int i = 0; i < n; i++) {
            if (selected.contains(cellOf[i])) {
                retained.add(candidates.get(i));
            }
        }
        retained.sort(BlockPoint::compareTo);
        return retained;
    }

    // ---------------------------------------------------------------- Kernel A

    private List<BlockPoint> findChunksGpu(long seed, long minX, long maxX, long minZ, long maxZ,
                                           boolean circleFilter, int centerX, int centerZ, long radiusSq) {
        int minChunkX = Math.floorDiv(clampToInt(minX), 16);
        int maxChunkX = Math.floorDiv(clampToInt(maxX), 16);
        int minChunkZ = Math.floorDiv(clampToInt(minZ), 16);
        int maxChunkZ = Math.floorDiv(clampToInt(maxZ), 16);
        int spacing = 34;
        int minRegionX = Math.floorDiv(minChunkX, spacing) - 1;
        int maxRegionX = Math.floorDiv(maxChunkX, spacing) + 1;
        int minRegionZ = Math.floorDiv(minChunkZ, spacing) - 1;
        int maxRegionZ = Math.floorDiv(maxChunkZ, spacing) + 1;
        int rxCount = maxRegionX - minRegionX + 1;
        long total = (long) rxCount * (maxRegionZ - minRegionZ + 1);

        ArrayList<BlockPoint> result = new ArrayList<>();
        // Count buffer (4 bytes) reused across calls.
        if (this.aFlowCountPtr == null) {
            this.aFlowCountPtr = new CUdeviceptr();
            cuMemAlloc(this.aFlowCountPtr, 4L);
        }
        CUdeviceptr countPtr = this.aFlowCountPtr;
        try {
            long start = 0;
            while (start < total) {
                long end = Math.min(total, start + BATCH_LIMIT);
                int capacity = (int) (end - start);
                // Grow the reused output buffer only when this batch needs more than the largest
                // seen so far — no per-call allocation, and batch-to-batch reuse within a call.
                if (capacity > this.aFlowOutCapacity) {
                    if (this.aFlowOutPtr != null) {
                        cuMemFree(this.aFlowOutPtr);
                    }
                    this.aFlowOutPtr = new CUdeviceptr();
                    cuMemAlloc(this.aFlowOutPtr, (long) capacity * 8L);
                    this.aFlowOutCapacity = capacity;
                }
                CUdeviceptr outPtr = this.aFlowOutPtr;
                cuMemsetD32(countPtr, 0, 1);
                int grid = (int) Math.ceil(capacity / (double) BLOCK);
                long tLaunch = System.nanoTime();
                cuLaunchKernel(fGenerateChunks,
                        grid, 1, 1, BLOCK, 1, 1, 0, null,
                        Pointer.to(
                                Pointer.to(new long[]{seed}),
                                Pointer.to(new int[]{minRegionX}),
                                Pointer.to(new int[]{minRegionZ}),
                                Pointer.to(new int[]{rxCount}),
                                Pointer.to(new long[]{start}),
                                Pointer.to(new long[]{end}),
                                Pointer.to(new int[]{clampToInt(minX)}),
                                Pointer.to(new int[]{clampToInt(maxX)}),
                                Pointer.to(new int[]{clampToInt(minZ)}),
                                Pointer.to(new int[]{clampToInt(maxZ)}),
                                Pointer.to(new int[]{circleFilter ? 1 : 0}),
                                Pointer.to(new int[]{centerX}),
                                Pointer.to(new int[]{centerZ}),
                                Pointer.to(new long[]{radiusSq}),
                                Pointer.to(outPtr),
                                Pointer.to(countPtr),
                                Pointer.to(new int[]{capacity})),
                        null);
                int[] count = new int[1];
                cuMemcpyDtoH(Pointer.to(count), countPtr, 4L);
                long tCount = System.nanoTime();
                int n = count[0];
                long tObj = System.nanoTime();
                if (n > 0) {
                    // Pre-size so the ArrayList never reallocates; the per-batch count is known.
                    result.ensureCapacity(result.size() + n);
                    int[] data = new int[n * 2];
                    cuMemcpyDtoH(Pointer.to(data), outPtr, n * 8L);
                    for (int i = 0; i < n; i++) {
                        result.add(new BlockPoint(data[2 * i], data[2 * i + 1]));
                    }
                }
                if (System.getProperty("trialfinder.trace.aflow") != null) {
                    System.out.printf("[aflow] cap=%d grid=%d n=%d kernel+countD2H=%.1fms obj=%.1fms%n",
                            capacity, grid, n, (tCount - tLaunch) / 1e6, (System.nanoTime() - tObj) / 1e6);
                }
                start = end;
            }
        } finally {
            // count/out buffers are intentionally kept for reuse across calls (no free here).
        }
        result.sort(BlockPoint::compareTo);
        return result;
    }

    // ---------------------------------------------------------------- GPU-direct grid prefilter (A-flow → grid)

    /**
     * GPU-direct grid prefilter for huge single-region searches. Enumerates candidate chambers
     * entirely on the GPU, computes their density scores on the GPU, aggregates those scores into
     * grid cells, selects the top-K cells by total density (the same criterion as the host
     * {@link #gridAggregateAndSelect}), and returns only the candidates inside the selected cells.
     *
     * <p>This reproduces the host grid-prefilter result while avoiding constructing millions of
     * {@link BlockPoint} objects in Java (the real A-flow bottleneck for large radii — the
     * enumerate kernel itself finishes in ~2ms; host object allocation + GC was the slowdown).
     *
     * @return candidates inside the top-K grid cells (sorted, de-duplicated)
     */
    public List<BlockPoint> findChunksGridPrefiltered(
            long seed, long minX, long maxX, long minZ, long maxZ,
            boolean circleFilter, int centerX, int centerZ, long radiusSq,
            int clusterRadius, int gridSize, int topK) {
        int minChunkX = Math.floorDiv(clampToInt(minX), 16);
        int maxChunkX = Math.floorDiv(clampToInt(maxX), 16);
        int minChunkZ = Math.floorDiv(clampToInt(minZ), 16);
        int maxChunkZ = Math.floorDiv(clampToInt(maxZ), 16);
        int spacing = 34;
        int minRegionX = Math.floorDiv(minChunkX, spacing) - 1;
        int maxRegionX = Math.floorDiv(maxChunkX, spacing) + 1;
        int minRegionZ = Math.floorDiv(minChunkZ, spacing) - 1;
        int maxRegionZ = Math.floorDiv(maxChunkZ, spacing) + 1;
        int rxCount = maxRegionX - minRegionX + 1;
        long total = (long) rxCount * (maxRegionZ - minRegionZ + 1);
        if (total <= 0) {
            return List.of();
        }

        // Pass 1: enumerate candidates straight into the reused device buffer (no host round-trip).
        int n = enumerateToGpu(seed, minRegionX, minRegionZ, rxCount, total,
                clampToInt(minX), clampToInt(maxX), clampToInt(minZ), clampToInt(maxZ),
                circleFilter, centerX, centerZ, radiusSq);
        if (n == 0) {
            return List.of();
        }
        if (n > DENSITY_BATCH_LIMIT) {
            throw new IllegalStateException("density batch too large: " + n);
        }
        CUdeviceptr pointsPtr = this.aFlowOutPtr; // int2[n] candidates from pass 1

        // Compute the candidate extent on the host (a plain int[] scan, NOT BlockPoint objects) so
        // the density and aggregation grids use the same origin as the host gridAggregateAndSelect —
        // otherwise cell boundaries shift and the top-K selection differs.
        int[] hostPoints = new int[n * 2];
        cuMemcpyDtoH(Pointer.to(hostPoints), pointsPtr, (long) n * 8L);
        int cMinX = Integer.MAX_VALUE, cMaxX = Integer.MIN_VALUE;
        int cMinZ = Integer.MAX_VALUE, cMaxZ = Integer.MIN_VALUE;
        for (int i = 0; i < n; i++) {
            int x = hostPoints[2 * i];
            int z = hostPoints[2 * i + 1];
            if (x < cMinX) cMinX = x;
            if (x > cMaxX) cMaxX = x;
            if (z < cMinZ) cMinZ = z;
            if (z > cMaxZ) cMaxZ = z;
        }
        int gridOriginX = cMinX;
        int gridOriginZ = cMinZ;
        long spanX = (long) cMaxX - cMinX;
        long spanZ = (long) cMaxZ - cMinZ;

        // Pass 2: density scores on the GPU (2R neighbour count), reusing the host density pipeline
        // but with the candidate buffer already on device.
        int densityCell = Math.max(1, clusterRadius * 2);
        long radius2Sq = (long) densityCell * densityCell;
        long dCellsLong = (spanX / densityCell + 1) * (spanZ / densityCell + 1);
        if (dCellsLong > DENSITY_CELL_LIMIT) {
            long minCell = (long) Math.ceil(Math.max(spanX, spanZ) / Math.sqrt(DENSITY_CELL_LIMIT));
            densityCell = Math.max(densityCell, (int) Math.min(Integer.MAX_VALUE, minCell));
        }
        int dDimX = (int) (spanX / densityCell + 1);
        int dDimZ = (int) (spanZ / densityCell + 1);
        int dCells = dDimX * dDimZ;

        // Reuse device buffers across tiles (allocating ~200MB per tile on Windows is very slow).
        ensureBuffer(dCells * 4L, () -> this.dCellCountPtr, v -> this.dCellCountPtr = v,
                () -> this.dCellCountCap, c -> this.dCellCountCap = c);
        ensureBuffer((long) (dCells + 1) * 4L, () -> this.dCellStartPtr, v -> this.dCellStartPtr = v,
                () -> this.dCellStartCap, c -> this.dCellStartCap = c);
        ensureBuffer(dCells * 4L, () -> this.dCellCursorPtr, v -> this.dCellCursorPtr = v,
                () -> this.dCellCursorCap, c -> this.dCellCursorCap = c);
        ensureBuffer((long) n * 4L, () -> this.dCellPointsPtr, v -> this.dCellPointsPtr = v,
                () -> this.dCellPointsCap, c -> this.dCellPointsCap = c);
        ensureBuffer((long) n * 4L, () -> this.dScoresPtr, v -> this.dScoresPtr = v,
                () -> this.dScoresCap, c -> this.dScoresCap = c);
        CUdeviceptr dCellCount = this.dCellCountPtr;
        CUdeviceptr dCellStart = this.dCellStartPtr;
        CUdeviceptr dCellCursor = this.dCellCursorPtr;
        CUdeviceptr dCellPoints = this.dCellPointsPtr;
        CUdeviceptr scoresPtr = this.dScoresPtr;

        // Pass 3: aggregate density scores into grid cells (the gridSize cell, not the density cell).
        long gCellsLong = (spanX / gridSize + 1) * (spanZ / gridSize + 1);
        if (gCellsLong > DENSITY_CELL_LIMIT) {
            long minCell = (long) Math.ceil(Math.max(spanX, spanZ) / Math.sqrt(DENSITY_CELL_LIMIT));
            int enlarged = Math.max(gridSize, (int) Math.min(Integer.MAX_VALUE, minCell));
            gridSize = enlarged;
        }
        int gDimX = (int) (spanX / gridSize + 1);
        int gDimZ = (int) (spanZ / gridSize + 1);
        int gCells = gDimX * gDimZ;

        ensureBuffer((long) gCells * 4L, () -> this.dGridScoresPtr, v -> this.dGridScoresPtr = v,
                () -> this.dGridScoresCap, c -> this.dGridScoresCap = c);
        ensureBuffer((long) gCells * 4L, () -> this.dGridCountsPtr, v -> this.dGridCountsPtr = v,
                () -> this.dGridCountsCap, c -> this.dGridCountsCap = c);
        CUdeviceptr gridScoresPtr = this.dGridScoresPtr;
        CUdeviceptr gridCountsPtr = this.dGridCountsPtr;

        ArrayList<BlockPoint> result = new ArrayList<>();
        try {
            // --- density (2R spatial hash) ---
            int grid = (int) Math.ceil(n / (double) BLOCK);
            cuMemsetD32(dCellCount, 0, dCells);
            cuMemsetD32(dCellCursor, 0, dCells);
            cuLaunchKernel(fCellCount, grid, 1, 1, BLOCK, 1, 1, 0, null,
                    Pointer.to(
                            Pointer.to(new int[]{n}), Pointer.to(pointsPtr),
                            Pointer.to(new int[]{gridOriginX}), Pointer.to(new int[]{gridOriginZ}),
                            Pointer.to(new int[]{dDimX}), Pointer.to(new int[]{dDimZ}),
                            Pointer.to(new int[]{densityCell}), Pointer.to(dCellCount)),
                    null);
            int[] dCount = new int[dCells];
            cuMemcpyDtoH(Pointer.to(dCount), dCellCount, (long) dCells * 4L);
            int[] dStart = new int[dCells + 1];
            for (int i = 0; i < dCells; i++) {
                dStart[i + 1] = dStart[i] + dCount[i];
            }
            cuMemcpyHtoD(dCellStart, Pointer.to(dStart), (long) (dCells + 1) * 4L);
            cuLaunchKernel(fScatter, grid, 1, 1, BLOCK, 1, 1, 0, null,
                    Pointer.to(
                            Pointer.to(new int[]{n}), Pointer.to(pointsPtr),
                            Pointer.to(new int[]{gridOriginX}), Pointer.to(new int[]{gridOriginZ}),
                            Pointer.to(new int[]{dDimX}), Pointer.to(new int[]{dDimZ}),
                            Pointer.to(new int[]{densityCell}), Pointer.to(dCellStart),
                            Pointer.to(dCellCursor), Pointer.to(dCellPoints)),
                    null);
            cuLaunchKernel(fCount, grid, 1, 1, BLOCK, 1, 1, 0, null,
                    Pointer.to(
                            Pointer.to(new int[]{n}), Pointer.to(pointsPtr),
                            Pointer.to(dCellStart), Pointer.to(dCellPoints),
                            Pointer.to(new int[]{gridOriginX}), Pointer.to(new int[]{gridOriginZ}),
                            Pointer.to(new int[]{dDimX}), Pointer.to(new int[]{dDimZ}),
                            Pointer.to(new int[]{densityCell}), Pointer.to(new long[]{radius2Sq}),
                            Pointer.to(scoresPtr)),
                    null);

            // --- grid aggregate (gridSize cells, density-weighted) ---
            if (System.getProperty("trialfinder.trace.aflow") != null) {
                System.out.printf("[gd] n=%d dCells=%d gCells=%d gridDim=%dx%d gridSize=%d%n",
                        n, dCells, gCells, gDimX, gDimZ, gridSize);
            }
            cuMemsetD32(gridScoresPtr, 0, gCells);
            cuMemsetD32(gridCountsPtr, 0, gCells);
            cuLaunchKernel(fGridAggregate, grid, 1, 1, BLOCK, 1, 1, 0, null,
                    Pointer.to(
                            Pointer.to(new int[]{n}), Pointer.to(pointsPtr), Pointer.to(scoresPtr),
                            Pointer.to(new int[]{gridOriginX}), Pointer.to(new int[]{gridOriginZ}),
                            Pointer.to(new int[]{gDimX}), Pointer.to(new int[]{gDimZ}),
                            Pointer.to(new int[]{gridSize}),
                            Pointer.to(gridScoresPtr), Pointer.to(gridCountsPtr)),
                    null);

            int[] gridScores = new int[gCells];
            cuMemcpyDtoH(Pointer.to(gridScores), gridScoresPtr, (long) gCells * 4L);

            // --- CPU top-K cell selection (density-weighted, ties by cell index) ---
            Integer[] sortedCells = new Integer[gCells];
            for (int c = 0; c < gCells; c++) {
                sortedCells[c] = c;
            }
            int[] gs = gridScores;
            java.util.Arrays.sort(sortedCells, (a, b) -> {
                int by = Integer.compare(gs[b], gs[a]);
                return by != 0 ? by : Integer.compare(a, b);
            });
            int keep = Math.min(topK, gCells);
            byte[] selected = new byte[gCells];
            for (int i = 0; i < keep; i++) {
                if (gs[sortedCells[i]] > 0) {
                    selected[sortedCells[i]] = 1;
                }
            }

            // --- collect candidates in selected grid cells (re-enumerate) ---
            CUdeviceptr selectedPtr = new CUdeviceptr();
            cuMemAlloc(selectedPtr, (long) gCells);
            cuMemcpyHtoD(selectedPtr, Pointer.to(selected), (long) gCells);
            CUdeviceptr outPtr = new CUdeviceptr();
            cuMemAlloc(outPtr, (long) gCells * 8L); // upper bound: one candidate per cell
            CUdeviceptr countPtr = new CUdeviceptr();
            cuMemAlloc(countPtr, 4L);
            try {
                cuMemsetD32(countPtr, 0, 1);
                long start = 0;
                while (start < total) {
                    long end = Math.min(total, start + BATCH_LIMIT);
                    int capacity = (int) (end - start);
                    int g = (int) Math.ceil(capacity / (double) BLOCK);
                    cuLaunchKernel(fGridCollect, g, 1, 1, BLOCK, 1, 1, 0, null,
                            Pointer.to(
                                    Pointer.to(new long[]{seed}),
                                    Pointer.to(new int[]{minRegionX}), Pointer.to(new int[]{minRegionZ}),
                                    Pointer.to(new int[]{rxCount}),
                                    Pointer.to(new long[]{start}), Pointer.to(new long[]{end}),
                                    Pointer.to(new int[]{clampToInt(minX)}), Pointer.to(new int[]{clampToInt(maxX)}),
                                    Pointer.to(new int[]{clampToInt(minZ)}), Pointer.to(new int[]{clampToInt(maxZ)}),
                                    Pointer.to(new int[]{circleFilter ? 1 : 0}),
                                    Pointer.to(new int[]{centerX}), Pointer.to(new int[]{centerZ}),
                                    Pointer.to(new long[]{radiusSq}),
                                    Pointer.to(new int[]{gridOriginX}), Pointer.to(new int[]{gridOriginZ}),
                                    Pointer.to(new int[]{gDimX}), Pointer.to(new int[]{gDimZ}),
                                    Pointer.to(new int[]{gridSize}),
                                    Pointer.to(selectedPtr), Pointer.to(outPtr), Pointer.to(countPtr),
                                    Pointer.to(new int[]{capacity})),
                            null);
                    start = end;
                }
                int[] count = new int[1];
                cuMemcpyDtoH(Pointer.to(count), countPtr, 4L);
                int cnt = count[0];
                if (cnt > 0) {
                    int[] data = new int[cnt * 2];
                    cuMemcpyDtoH(Pointer.to(data), outPtr, cnt * 8L);
                    result.ensureCapacity(cnt);
                    for (int i = 0; i < cnt; i++) {
                        result.add(new BlockPoint(data[2 * i], data[2 * i + 1]));
                    }
                }
            } finally {
                cuMemFree(selectedPtr);
                cuMemFree(outPtr);
                cuMemFree(countPtr);
            }
        } finally {
            // Reused device buffers (dCell*, scores, grid*) are intentionally kept across calls.
        }
        result.sort(BlockPoint::compareTo);
        return result;
    }

    /**
     * Enumerates candidate chambers into the reused {@link #aFlowOutPtr} device buffer, returning
     * the number produced. The buffer is sized to the largest batch so the returned candidate list
     * lives entirely on the GPU (no host object allocation).
     */
    private int enumerateToGpu(long seed, int minRegionX, int minRegionZ, int rxCount, long total,
                               int minX, int maxX, int minZ, int maxZ,
                               boolean circleFilter, int centerX, int centerZ, long radiusSq) {
        if (this.aFlowCountPtr == null) {
            this.aFlowCountPtr = new CUdeviceptr();
            cuMemAlloc(this.aFlowCountPtr, 4L);
        }
        CUdeviceptr countPtr = this.aFlowCountPtr;
        int totalN = 0;
        long start = 0;
        while (start < total) {
            long end = Math.min(total, start + BATCH_LIMIT);
            int capacity = (int) (end - start);
            if (capacity > this.aFlowOutCapacity) {
                if (this.aFlowOutPtr != null) {
                    cuMemFree(this.aFlowOutPtr);
                }
                this.aFlowOutPtr = new CUdeviceptr();
                cuMemAlloc(this.aFlowOutPtr, (long) capacity * 8L);
                this.aFlowOutCapacity = capacity;
            }
            CUdeviceptr outPtr = this.aFlowOutPtr;
            cuMemsetD32(countPtr, 0, 1);
            int grid = (int) Math.ceil(capacity / (double) BLOCK);
            cuLaunchKernel(fGenerateChunks, grid, 1, 1, BLOCK, 1, 1, 0, null,
                    Pointer.to(
                            Pointer.to(new long[]{seed}),
                            Pointer.to(new int[]{minRegionX}), Pointer.to(new int[]{minRegionZ}),
                            Pointer.to(new int[]{rxCount}),
                            Pointer.to(new long[]{start}), Pointer.to(new long[]{end}),
                            Pointer.to(new int[]{minX}), Pointer.to(new int[]{maxX}),
                            Pointer.to(new int[]{minZ}), Pointer.to(new int[]{maxZ}),
                            Pointer.to(new int[]{circleFilter ? 1 : 0}),
                            Pointer.to(new int[]{centerX}), Pointer.to(new int[]{centerZ}),
                            Pointer.to(new long[]{radiusSq}),
                            Pointer.to(outPtr), Pointer.to(countPtr),
                            Pointer.to(new int[]{capacity})),
                    null);
            int[] count = new int[1];
            cuMemcpyDtoH(Pointer.to(count), countPtr, 4L);
            totalN += count[0];
            start = end;
        }
        return totalN;
    }

    /** Grows a reused device buffer to at least {@code bytes}; no-op when already large enough. */
    private void ensureBuffer(long bytes,
                              java.util.function.Supplier<CUdeviceptr> getter,
                              java.util.function.Consumer<CUdeviceptr> setter,
                              java.util.function.IntSupplier capGetter,
                              java.util.function.IntConsumer capSetter) {
        CUdeviceptr ptr = getter.get();
        if (ptr != null && bytes <= capGetter.getAsInt()) {
            return;
        }
        if (ptr != null) {
            cuMemFree(ptr);
        }
        CUdeviceptr fresh = new CUdeviceptr();
        cuMemAlloc(fresh, bytes);
        setter.accept(fresh);
        capSetter.accept((int) bytes);
    }

