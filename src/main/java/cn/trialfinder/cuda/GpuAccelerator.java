    private int[] densityCountsGpu(List<BlockPoint> candidates, int clusterRadius) {
        int n = candidates.size();
        int[] counts = new int[n];
        if (n == 0) {
            return counts;
        }
        if (n > DENSITY_BATCH_LIMIT) {
            throw new IllegalStateException("density batch too large: " + n);
        }
        // Density neighbour criterion radius (2R) is fixed; the spatial hash cell is enlarged when
        // the grid would exceed DENSITY_CELL_LIMIT. Enlarging the cell is lossless: a coarser grid
        // still covers every neighbour within 2R in the 3x3 neighbourhood, so counts are unchanged.
        int cellSize = Math.max(1, clusterRadius * 2);
        long radiusSq = (long) cellSize * cellSize;

        int minX = Integer.MAX_VALUE;
        int maxX = Integer.MIN_VALUE;
        int minZ = Integer.MAX_VALUE;
        int maxZ = Integer.MIN_VALUE;
        for (BlockPoint p : candidates) {
            minX = Math.min(minX, p.x());
            maxX = Math.max(maxX, p.x());
            minZ = Math.min(minZ, p.z());
            maxZ = Math.max(maxZ, p.z());
        }
        long spanX = (long) maxX - minX;
        long spanZ = (long) maxZ - minZ;
        long cells = (spanX / cellSize + 1) * (spanZ / cellSize + 1);
        if (cells > DENSITY_CELL_LIMIT) {
            long minCell = (long) Math.ceil(Math.max(spanX, spanZ) / Math.sqrt(DENSITY_CELL_LIMIT));
            int enlarged = Math.max(cellSize, (int) Math.min(Integer.MAX_VALUE, minCell));
            if (System.getProperty("trialfinder.debug.cells") != null) {
                System.out.printf("[density] cells %,d > limit, cellSize %d -> %d%n", cells, cellSize, enlarged);
            }
            cellSize = enlarged;
        }
        int gridDimX = (int) (spanX / cellSize + 1);
        int gridDimZ = (int) (spanZ / cellSize + 1);
        int cellsUsed = gridDimX * gridDimZ;

        int[] points = new int[n * 2];
        for (int i = 0; i < n; i++) {
            points[2 * i] = candidates.get(i).x();
            points[2 * i + 1] = candidates.get(i).z();
        }

        CUdeviceptr ptsPtr = new CUdeviceptr();
        cuMemAlloc(ptsPtr, (long) n * 8L);
        CUdeviceptr cellCountPtr = new CUdeviceptr();
        cuMemAlloc(cellCountPtr, (long) cellsUsed * 4L);
        CUdeviceptr cellStartPtr = new CUdeviceptr();
        cuMemAlloc(cellStartPtr, (long) (cellsUsed + 1) * 4L);
        CUdeviceptr cellCursorPtr = new CUdeviceptr();
        cuMemAlloc(cellCursorPtr, (long) cellsUsed * 4L);
        CUdeviceptr cellPointsPtr = new CUdeviceptr();
        cuMemAlloc(cellPointsPtr, (long) n * 4L);
        CUdeviceptr countsPtr = new CUdeviceptr();
        cuMemAlloc(countsPtr, (long) n * 4L);

        try {
            cuMemcpyHtoD(ptsPtr, Pointer.to(points), (long) n * 8L);
            cuMemsetD32(cellCountPtr, 0, cellsUsed);
            cuMemsetD32(cellCursorPtr, 0, cellsUsed);

            int grid = (int) Math.ceil(n / (double) BLOCK);

            cuLaunchKernel(fCellCount,
                    grid, 1, 1, BLOCK, 1, 1, 0, null,
                    Pointer.to(
                            Pointer.to(new int[]{n}),
                            Pointer.to(ptsPtr),
                            Pointer.to(new int[]{minX}),
                            Pointer.to(new int[]{minZ}),
                            Pointer.to(new int[]{gridDimX}),
                            Pointer.to(new int[]{gridDimZ}),
                            Pointer.to(new int[]{cellSize}),
                            Pointer.to(cellCountPtr)),
                    null);

            int[] cellCount = new int[cellsUsed];
            cuMemcpyDtoH(Pointer.to(cellCount), cellCountPtr, (long) cellsUsed * 4L);
            int[] cellStart = new int[cellsUsed + 1];
            for (int i = 0; i < cellsUsed; i++) {
                cellStart[i + 1] = cellStart[i] + cellCount[i];
            }
            cuMemcpyHtoD(cellStartPtr, Pointer.to(cellStart), (long) (cellsUsed + 1) * 4L);

            cuLaunchKernel(fScatter,
                    grid, 1, 1, BLOCK, 1, 1, 0, null,
                    Pointer.to(
                            Pointer.to(new int[]{n}),
                            Pointer.to(ptsPtr),
                            Pointer.to(new int[]{minX}),
                            Pointer.to(new int[]{minZ}),
                            Pointer.to(new int[]{gridDimX}),
                            Pointer.to(new int[]{gridDimZ}),
                            Pointer.to(new int[]{cellSize}),
                            Pointer.to(cellStartPtr),
                            Pointer.to(cellCursorPtr),
                            Pointer.to(cellPointsPtr)),
                    null);

            cuLaunchKernel(fCount,
                    grid, 1, 1, BLOCK, 1, 1, 0, null,
                    Pointer.to(
                            Pointer.to(new int[]{n}),
                            Pointer.to(ptsPtr),
                            Pointer.to(cellStartPtr),
                            Pointer.to(cellPointsPtr),
                            Pointer.to(new int[]{minX}),
                            Pointer.to(new int[]{minZ}),
                            Pointer.to(new int[]{gridDimX}),
                            Pointer.to(new int[]{gridDimZ}),
                            Pointer.to(new int[]{cellSize}),
                            Pointer.to(new long[]{radiusSq}),
                            Pointer.to(countsPtr)),
                    null);

            cuMemcpyDtoH(Pointer.to(counts), countsPtr, (long) n * 4L);
        } finally {
            cuMemFree(ptsPtr);
            cuMemFree(cellCountPtr);
            cuMemFree(cellStartPtr);
            cuMemFree(cellCursorPtr);
            cuMemFree(cellPointsPtr);
            cuMemFree(countsPtr);
        }
        return counts;
    }

    // ---------------------------------------------------------------- precompiled cubin loading

    /**
     * Attempts to load a precompiled cubin for {@code arch} (e.g. {@code "sm_89"}) from the
     * classpath ({@code /cuda/trial_finder_<arch>.cubin}, generated by {@code compileCubin}).
     * Returns the loaded module, or {@code null} when no cubin is bundled or it fails to load —
     * the caller then falls back to NVRTC + ptxas.
     */
    private static CUmodule tryLoadPrecompiledCubin(String arch, long tStart) {
        String resource = "/cuda/trial_finder_" + arch + ".cubin";
        try (InputStream in = GpuAccelerator.class.getResourceAsStream(resource)) {
            if (in == null) {
                System.out.println("[DEBUG] no precompiled cubin on classpath for " + arch
                        + " (" + resource + "); using NVRTC + ptxas");
                return null;
            }
            byte[] data = in.readAllBytes();
            CUmodule module = new CUmodule();
            cuModuleLoadData(module, data);
            long tLoaded = System.nanoTime();
            System.out.printf("[DEBUG] loaded precompiled cubin %s (%d bytes) in %.1f ms%n",
                    arch, data.length, (tLoaded - tStart) / 1e6);
            return module;
        } catch (IOException e) {
            System.out.println("[DEBUG] failed to read precompiled cubin " + resource + ": "
                    + e.getMessage() + "; using NVRTC + ptxas");
            return null;
        } catch (Throwable t) {
            // cuModuleLoadData throws when the cubin arch does not match the device; the module
            // is discarded and the NVRTC fallback recompiles for the actual arch.
            System.out.println("[DEBUG] failed to load precompiled cubin " + arch + ": "
                    + t.getClass().getSimpleName() + ": " + t.getMessage() + "; using NVRTC + ptxas");
            return null;
        }
    }

    // ---------------------------------------------------------------- NVRTC + PTX cache

    /** Compiles source→PTX via NVRTC, cached on disk keyed by (source-hash, arch). */
    private static String cachedPtx(String source, String arch) {
        String key = sha256(source + "|" + arch);
        Path cacheDir = Path.of(System.getProperty("trialfinder.ptx.cache",
                System.getProperty("java.io.tmpdir", "/tmp") + "/trialfinder-cubin"));
        Path cached = cacheDir.resolve("kernels-" + key + ".ptx");
        try {
            if (Files.isRegularFile(cached)) {
                return Files.readString(cached, StandardCharsets.UTF_8);
            }
        } catch (IOException e) {
            // fall through to fresh compile
        }
        String ptx = NvrtcCompiler.compile(source, arch);
        try {
            Files.createDirectories(cacheDir);
            Files.writeString(cached, ptx, StandardCharsets.UTF_8);
        } catch (IOException ignored) {
            // best-effort cache write
        }
        return ptx;
    }

    private static String sha256(String text) {
        try {
            byte[] hash = java.security.MessageDigest.getInstance("SHA-256")
                    .digest(text.getBytes(StandardCharsets.UTF_8));
            StringBuilder sb = new StringBuilder(hash.length * 2);
            for (byte b : hash) {
                sb.append(String.format("%02x", b));
            }
            return sb.toString();
        } catch (java.security.NoSuchAlgorithmException e) {
            return Integer.toHexString(text.hashCode());
        }
    }

    private static String loadKernelSource() throws IOException {
        try (InputStream in = GpuAccelerator.class.getResourceAsStream("/cuda/trial_finder_kernels.cu")) {
            if (in == null) {
                throw new IOException("kernel source not found on classpath: /cuda/trial_finder_kernels.cu");
            }
            return new String(in.readAllBytes(), StandardCharsets.UTF_8);
        }
    }

    private static int clampToInt(long value) {
        return (int) Math.max(Integer.MIN_VALUE, Math.min(Integer.MAX_VALUE, value));
    }
